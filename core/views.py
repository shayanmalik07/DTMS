@extend_schema(summary="Approve/Reject Officer Registration", description="Supervisor decides officer pending registration")
@api_view(['POST'])
@permission_classes([IsSupervisor])
def decide_officer_registration(request, officer_id):
    officer = get_object_or_404(User, pk=officer_id, supervisor=request.user)
    action = request.data.get('action') # 'approve' or 'reject'
    
    if action == 'approve':
        officer.status = User.Status.ACTIVE
    elif action == 'reject':
        officer.status = User.Status.REJECTED
    else:
        return Response({'error': 'Invalid action. Use "approve" or "reject"'}, status=status.HTTP_400_BAD_REQUEST)
    
    officer.save()
    return Response({'message': f'Officer registration status updated to {officer.status}'})


