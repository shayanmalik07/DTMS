@extend_schema(
    summary="User Login",
    description="Authenticate any user and return JWT tokens",
    request=LoginSerializer,  # <--- Tells Swagger to display email & password fields!
)
@api_view(['POST'])
@permission_classes([permissions.AllowAny])
def login_view(request):
    email = request.data.get('email')
    password = request.data.get('password')

    user = User.objects.filter(email=email).first()
    if not user or not user.check_password(password):
        return Response({'error': 'Invalid credentials'}, status=status.HTTP_401_UNAUTHORIZED)

    if user.status != User.Status.ACTIVE:
        return Response({'error': f'Account is {user.status}. Access denied.'}, status=status.HTTP_403_FORBIDDEN)

    refresh = RefreshToken.for_user(user)
    return Response({
        'refresh': str(refresh),
        'access': str(refresh.access_token),
        'role': user.role,
        'user_id': user.pk
    })


@extend_schema(summary="Generate Officer Invite Link", description="Supervisor generates invitation token for officer registration")
@api_view(['POST'])
@permission_classes([IsSupervisor])
def generate_invite_link(request):
    token = signer.sign(f"supervisor:{request.user.pk}")
    invite_url = f"https://yourapp.com/register?token={token}"
    return Response({'invite_token': token, 'invite_url': invite_url})


@extend_schema(
    summary="Register Officer",
    description="Officer registers using invite token received from Supervisor",
    request=RegisterOfficerSerializer,  # <--- Shows JSON body in Swagger
    parameters=[
        OpenApiParameter(
            name='token',
            type=str,
            location=OpenApiParameter.QUERY,
            required=True,
            description='Invite token generated by Supervisor'
        )
    ]
)
@api_view(['POST'])
@permission_classes([permissions.AllowAny])
def register_officer(request):
    token = request.query_params.get('token')
    if not token:
        return Response({'error': 'Invite token is required'}, status=status.HTTP_400_BAD_REQUEST)
    
    try:
        unsigned_data = signer.unsign(token, max_age=172800)
        supervisor_id = unsigned_data.split(':')[1]
    except (BadSignature, SignatureExpired):
        return Response({'error': 'Invalid or expired invite token'}, status=status.HTTP_400_BAD_REQUEST)

    email = request.data.get('email')
    password = request.data.get('password')
    name = request.data.get('name')
    phone = request.data.get('phone')

    if User.objects.filter(email=email).exists():
        return Response({'error': 'Email already exists'}, status=status.HTTP_400_BAD_REQUEST)

    supervisor = User.objects.get(pk=supervisor_id)
    user = User.objects.create_user(
        email=email,
        password=password,
        name=name,
        phone=phone,
        role=User.Role.OFFICER,
        status=User.Status.PENDING,
        supervisor=supervisor
    )
    return Response({'message': 'Officer registered successfully. Pending approval.'}, status=status.HTTP_201_CREATED)


