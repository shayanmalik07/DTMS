@extend_schema(summary="Send Direct Message", description="Send 1-on-1 message between officer and supervisor")
@api_view(['POST'])
@permission_classes([permissions.IsAuthenticated])
def send_message(request):
    sender = request.user
    content = request.data.get('message')

    if sender.role == User.Role.OFFICER:
        msg = Message.objects.create(
            sender=sender, receiver=sender.supervisor, supervisor=sender.supervisor,
            message=content, is_broadcast=False
        )
    else:
        receiver_id = request.data.get('receiver_id')
        receiver = get_object_or_404(User, pk=receiver_id, supervisor=sender)
        msg = Message.objects.create(
            sender=sender, receiver=receiver, supervisor=sender,
            message=content, is_broadcast=False
        )
    return Response(MessageSerializer(msg).data, status=status.HTTP_201_CREATED)


@extend_schema(summary="Broadcast Message", description="Supervisor sends broadcast message to all assigned officers")
@api_view(['POST'])
@permission_classes([IsSupervisor])
def broadcast_message(request):
    content = request.data.get('message')
    msg = Message.objects.create(
        sender=request.user, receiver=None, supervisor=request.user,
        message=content, is_broadcast=True
    )
    return Response({'message': 'Broadcast sent successfully', 'id': msg.pk}, status=status.HTTP_201_CREATED)


