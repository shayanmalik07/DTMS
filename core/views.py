@extend_schema(summary="Update Live Location", description="Officer sends live GPS coordinates during shift")
@api_view(['POST'])
@permission_classes([IsOfficer])
def update_location(request):
    lat = float(request.data.get('latitude'))
    lng = float(request.data.get('longitude'))
    
    LiveLocation.objects.update_or_create(
        officer=request.user,
        defaults={'latitude': lat, 'longitude': lng}
    )
    return Response({'status': 'Location updated'})


@extend_schema(summary="Get Officer Location", description="Supervisor fetches live location of assigned officer")
@api_view(['GET'])
@permission_classes([IsSupervisor])
def get_officer_location(request, officer_id):
    officer = get_object_or_404(User, pk=officer_id, supervisor=request.user)
    location = get_object_or_404(LiveLocation, officer=officer)
    
    return Response({
        'officer_id': officer.pk,
        'latitude': location.latitude,
        'longitude': location.longitude,
        'updated_at': location.updated_at
    })